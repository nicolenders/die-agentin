/**
 * Anklickbare Social-Media-Icons. Rein darstellend: erhält die gepflegten
 * Profile (Plattform → URL) und rendert nur die vorhandenen, in fester
 * Reihenfolge. Jeder Link öffnet in einem neuen Tab. Wird im Footer und auf der
 * Legende-Seite verwendet; die Optik kommt über `className`.
 */
export default function SocialLinks({
  social,
  className,
}: {
  social: Record<string, string>;
  className?: string;
}) {
  const links = SOCIAL_PLATFORMS.filter((p) => social[p.key]);
  if (links.length === 0) return null;
  return (
    <div className={className}>
      {links.map((p) => (
        <a
          key={p.key}
          href={social[p.key]}
          aria-label={p.label}
          title={p.label}
          target="_blank"
          rel="me noopener noreferrer"
        >
          {ICONS[p.key] ? (
            <svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" focusable="false">
              {ICONS[p.key]}
            </svg>
          ) : (
            p.icon
          )}
        </a>
      ))}
    </div>
  );
}
